export type SupportedUiLang =
  | 'it'
  | 'en'
  | 'es'
  | 'fr'
  | 'de'
  | 'pt'
  | 'ru'
  | 'zh'
  | 'ja'
  | 'ko'
  | 'ar';

export function normalizeUiLang(lang?: string): SupportedUiLang {
  const s = (lang || 'en').toLowerCase().trim();
  const supported: SupportedUiLang[] = [
    'it',
    'en',
    'es',
    'fr',
    'de',
    'pt',
    'ru',
    'zh',
    'ja',
    'ko',
    'ar',
  ];
  return (supported.includes(s as SupportedUiLang) ? s : 'en') as SupportedUiLang;
}

